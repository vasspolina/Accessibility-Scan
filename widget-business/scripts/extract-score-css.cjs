// One-off helper for the Gemini demo build: copies the product's score rules
// (every selector naming a11y-sum-* or a11y-score) and the root colour and
// spacing tokens out of global.css, in cascade order. Run from widget-business/:
//   node scripts/extract-score-css.cjs > src/styles/gemini-score.css
const fs = require("fs");
const postcss = require("postcss");

const root = postcss.parse(fs.readFileSync("src/styles/global.css", "utf8"));
const keep = /a11y-sum-|a11y-score\b/;
const isRoot = /^(\s*\.a11y-widget-biz(\[data-theme="dark"\]|:not\(\[data-theme="light"\]\))?\s*,?)+$/;
const tokens = postcss.root();
const rules = postcss.root();

function scan(node, tokParent, ruleParent) {
  node.each((ch) => {
    if (ch.type === "rule") {
      if (isRoot.test(ch.selector)) {
        const r = ch.clone();
        r.nodes = r.nodes.filter((d) => d.type === "decl" && d.prop.startsWith("--"));
        if (r.nodes.length) tokParent.append(r);
        return;
      }
      const sels = ch.selectors.filter((s) => keep.test(s));
      if (!sels.length) return;
      const r = ch.clone();
      r.selectors = sels;
      ruleParent.append(r);
    } else if (ch.type === "atrule" && /^(media|container|supports)$/.test(ch.name)) {
      const t = ch.clone({ nodes: [] });
      const r = ch.clone({ nodes: [] });
      scan(ch, t, r);
      if (t.nodes.length) tokParent.append(t);
      if (r.nodes.length) ruleParent.append(r);
    }
  });
}
scan(root, tokens, rules);

process.stdout.write(
  "/* Generated by scripts/extract-score-css.cjs from global.css: the product's\n" +
  "   tokens and its score block (user's instruction, 26 Nov 2026, \"keep colors\n" +
  "   from previous version\", \"and your score design\"). Do not edit by hand. */\n\n" +
  tokens.toString() + "\n\n" + rules.toString() + "\n"
);
